  /*! @brief Функция копирует заданное число байт из одной области памяти в другую область.
      @param dest Указатель на область памяти, куда помещаются значения.
      @param src Указатель на область памяти, откуда считываются значения.
      @param s Количество копируемых байт памяти.
      @return Функция возвращает указатель на заполненную область памяти. */
