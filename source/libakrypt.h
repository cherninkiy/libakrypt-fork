  /*! @brief Функция сравнивает в лексикографическом порядке две строки, оканчивающиеся нулем.
      @note Реализация функции из библиотеки libakrypt производит сравнение строк, длина которых
      не превышает значения макроса AK_DEFAULT_BUFFER_SIZE. Если символ ноль не встретился
      на такой длине у обеих строк, то функция возвращает ноль.
      @param s1 Первая строка, с которой производится сравнение.
      @param s2 Вторая строка, с которой производится сравнение.
      @return Функция возвращает: 0 - если строки совпадают, отрицательное число, если строка s1
      меньше чтроки s2, положительное число, если строка s1 больше, чем строка s2. */
  int strcmp( const char *s1, const char *s2 );

  /*! @brief Функция возвращает длину строки, оканчивающейся нулем.
      @note Реализация функции из библиотеки libakrypt вычисляет длину строки,
      не превосходящую значения макроса AK_DEFAULT_STATIC_BUFFER_SIZE. Если символ ноль
      не встретился на такой длине, то функция возвращает AK_DEFAULT_STATIC_BUFFER_SIZE.
      @param s Строка для которой вычисляется длина.
      @return Функция возвращает длину строки в байтах или ноль. */
  size_t strlen( const char *s );
