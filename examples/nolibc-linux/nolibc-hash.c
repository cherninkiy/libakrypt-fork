/*  Пример иллюстрирует процесс вызова функций хеширования с использованием          */
/*  стандартного механизма ak_hash (универсальный контекст алгоритмов хеширования)   */
/*                                                                                   */
/*  1. При компиляции примера должен применяться специально подготовленный           */
/*  файл libakrypt-config.h, отключающий подключение заголовков стандартной          */
/*  библиотеки языка Си и, как следствие, оптимизирующий код                         */
/*                                                                                   */
/*  2. При сборке примера должен использоваться флаг -nostdlib и явно указываться    */
/*  файлы с исходными текстами                                                       */
/*                                                                                   */
/*  3. Ассемблерные вставки используют системные вызовы linux и могут быть корректно */
/*  скомпилированы только под x64 архитектурой.                                      */
